const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require.resolve('../app.js'),'utf8');
const match=source.match(/function chartPreferenceRestorationNeeded\(mutations\)\{[\s\S]*?\r?\n\}\r?\n(?=document\.addEventListener\('DOMContentLoaded')/);
assert.ok(match,'preference observer predicate is available');
const check=vm.runInNewContext('('+match[0].trim()+')');
const element=(self='',child='',insidePlot=false)=>({nodeType:1,matches:selector=>selector==='select'?self==='select':selector==='.js-plotly-plot'?self==='plot':['input','select','option','collapse'].includes(self),querySelector:()=>child||null,closest:()=>insidePlot?{}:null});
const record=(target,addedNodes=[],removedNodes=[])=>({target,addedNodes,removedNodes});
assert.equal(check([record(element(),[element('input')])]),true,'new toggle');
assert.equal(check([record(element(),[element('','input')])]),true,'new filter container');
assert.equal(check([record(element(),[element('collapse')])]),true,'new collapsible button');
assert.equal(check([record(element(),[],[element('input')])]),true,'removed toggle updates empty summary');
assert.equal(check([record(element('select'))]),true,'options removed from select');
assert.equal(check([record(element(),[{nodeType:3}])]),false,'text update');
assert.equal(check([record(element('', '', true),[element('input')])]),false,'plot mutations');
assert.equal(check([record(element(),[element('plot','input')])]),false,'new Plotly subtree');
assert.equal(check([record(element(),[])]),false,'removed non-control subtree');
console.log('Preference observer ignores chart redraws and restores dynamic controls.');
